"""PR body generation and creation via gh/glab/file."""

from __future__ import annotations

import subprocess
from pathlib import Path
from typing import Any

from .config import git_settings
from .io_util import atomic_write_text
from .paths import kaotim_dir
from .plan import parse_plan, plan_path
from .state import read_state, write_state


def build_pr_body(repo: Path) -> dict[str, Any]:
    plan_text = ""
    parsed = None
    if plan_path(repo).exists():
        plan_text = plan_path(repo).read_text(encoding="utf-8")
        parsed = parse_plan(plan_text)
    meta = (parsed or {}).get("meta") or {}
    title = meta.get("title") or "Kaotim change"
    ac_rows = (parsed or {}).get("acceptance") or []
    lines = [
        f"## Purpose",
        meta.get("title") or "",
        "",
        "## Why / Expected outcome",
        "See `.kaotim/plan.md`.",
        "",
        "## What changed",
        "- Implemented per Kaotim plan tasks.",
        "",
        "## AC -> test -> status",
        "",
        "| AC | Criterion | Task | Status |",
        "|---|---|---|---|",
    ]
    for row in ac_rows:
        aid = row.get("ID") or row.get("Id") or ""
        crit = row.get("Criterion") or row.get("criterion") or ""
        task = row.get("Task") or ""
        lines.append(f"| {aid} | {crit} | {task} | pending |")
    lines.extend(
        [
            "",
            "## Decisions",
            "See plan decision log.",
            "",
            "## Risks and rollback",
            "See plan §7.",
            "",
            "## How to verify",
            "Run the project test suite and quality commands from `.kaotim/config.yaml` (`commands.*`).",
            "",
            "## Notes",
            "Generated by Kaotim.",
        ]
    )
    body = "\n".join(lines) + "\n"
    return {"title": title if title.startswith("feat") or ":" in title else f"feat: {title}", "body": body}


def create_pr(repo: Path, draft: bool = True) -> dict[str, Any]:
    built = build_pr_body(repo)
    pr_cli = (git_settings(repo).get("pr_cli")) or "gh"
    out_path = kaotim_dir(repo) / "pr.md"
    atomic_write_text(out_path, f"# {built['title']}\n\n{built['body']}")

    if pr_cli == "none":
        _mark_pr(repo)
        return {"ok": True, "mode": "file", "path": str(out_path), **built}

    cmd = None
    if pr_cli == "gh" and _which("gh"):
        cmd = [
            "gh",
            "pr",
            "create",
            "--title",
            built["title"],
            "--body",
            built["body"],
        ]
        if draft:
            cmd.append("--draft")
    elif pr_cli == "glab" and _which("glab"):
        cmd = ["glab", "mr", "create", "--title", built["title"], "--description", built["body"]]
        if draft:
            cmd.append("--draft")

    if not cmd:
        _mark_pr(repo)
        return {
            "ok": True,
            "mode": "file",
            "path": str(out_path),
            "warning": f"{pr_cli} unavailable; wrote pr.md",
            **built,
        }

    proc = subprocess.run(cmd, cwd=str(repo), capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        return {
            "ok": False,
            "mode": pr_cli,
            "error": proc.stderr or proc.stdout,
            "path": str(out_path),
            **built,
        }
    _mark_pr(repo)
    return {"ok": True, "mode": pr_cli, "stdout": proc.stdout, "path": str(out_path), **built}


def _mark_pr(repo: Path) -> None:
    state = read_state(repo)
    if not state:
        return
    gates = state.setdefault("gates", {})
    gates["pr_created"] = True
    state["gates"] = gates
    write_state(state, repo)


def _which(name: str) -> bool:
    from shutil import which

    return which(name) is not None
