"""kaotim-init / refresh / copy CLI into .kaotim/bin."""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Any

from . import PLUGIN_VERSION
from .detect import detect_stack, digest_to_stack_draft
from .io_util import atomic_write_text
from .markers import merge_marked
from .paths import ensure_kaotim_dirs, plugin_root
from .validate_stack import validate_stack
from .yaml_util import dump_yaml, load_yaml_file


def copy_cli_to_bin(repo: Path) -> Path:
    root = ensure_kaotim_dirs(repo)
    dest_dir = root / "bin"
    dest_dir.mkdir(parents=True, exist_ok=True)
    src = plugin_root() / "scripts"
    # copy kaotim.py and lib + vendor
    dest_script = dest_dir / "kaotim.py"
    shutil.copy2(src / "kaotim.py", dest_script)
    for name in ("lib", "vendor"):
        target = dest_dir / name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(src / name, target)
    # stamp version in a sidecar
    atomic_write_text(dest_dir / "VERSION", PLUGIN_VERSION + "\n")
    # ensure gitignore entries
    gi = repo / ".gitignore"
    needed = [
        ".kaotim/handoffs/",
        ".kaotim/gates/",
        ".kaotim/worktrees/",
        ".kaotim/metrics/*.jsonl",
        ".kaotim/state.json",
    ]
    existing = gi.read_text(encoding="utf-8") if gi.exists() else ""
    additions = [n for n in needed if n not in existing]
    if additions:
        atomic_write_text(gi, existing.rstrip() + "\n" + "\n".join(additions) + "\n")
    return dest_script


def write_stack_from_detect(repo: Path, force: bool = False) -> dict[str, Any]:
    digest = detect_stack(repo)
    draft = digest_to_stack_draft(digest)
    path = ensure_kaotim_dirs(repo) / "stack.yaml"
    if path.exists() and not force:
        existing = path.read_text(encoding="utf-8")
        generated = dump_yaml(draft)
        merged = merge_marked(existing, "stack", generated)
        # if no markers, don't overwrite user file — write draft alongside
        if "kaotim:generated:start:stack" not in existing:
            draft_path = ensure_kaotim_dirs(repo) / "stack.detected.yaml"
            atomic_write_text(draft_path, generated)
            return {
                "ok": True,
                "path": str(draft_path),
                "digest": digest,
                "note": "existing stack.yaml preserved; wrote stack.detected.yaml",
            }
        atomic_write_text(path, merged)
    else:
        atomic_write_text(path, dump_yaml(draft))
    vs = validate_stack(repo)
    return {"ok": vs["ok"], "path": str(path), "digest": digest, "validation": vs}


def write_profile(repo: Path) -> Path:
    path = ensure_kaotim_dirs(repo) / "project-profile.md"
    content = f"""# Project profile

Generated by Kaotim {PLUGIN_VERSION}.

## Architecture

Describe key modules, layers and entry points. Agents must search here before inventing helpers.

## Utilities to reuse

- (list existing helpers)

## Conventions

- Follow `.kaotim/stack.yaml` scopes and commands.
"""
    if path.exists():
        text = path.read_text(encoding="utf-8")
        atomic_write_text(path, merge_marked(text, "profile", content))
    else:
        atomic_write_text(path, content)
    return path


def refresh_proposals(repo: Path) -> dict[str, Any]:
    digest = detect_stack(repo)
    proposals = []
    stack_path = ensure_kaotim_dirs(repo) / "stack.yaml"
    if stack_path.exists():
        current = load_yaml_file(stack_path)
        draft = digest_to_stack_draft(digest)
        proposals.append(
            {
                "file": ".kaotim/stack.yaml",
                "action": "review-diff",
                "detected_stacks": [e.get("adapter") for e in digest.get("detected_ecosystems") or []],
                "draft_stack_count": len(((draft.get("packages") or [{}])[0].get("stacks") or [])),
                "note": "Diff only; will not overwrite user edits outside kaotim:generated markers.",
            }
        )
    else:
        proposals.append({"file": ".kaotim/stack.yaml", "action": "create", "note": "run /kaotim-stack"})
    return {"ok": True, "proposals": proposals, "digest": digest}
